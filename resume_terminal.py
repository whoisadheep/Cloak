def extract_keywords(text: str, top_n: int = 40) -> list[tuple[str, int]]:
    """Extract high-frequency non-stop keywords from text."""
    text = text.lower()
    text = re.sub(r'[^\w\s+#]', ' ', text)
    tokens = text.split()
    tokens = [t for t in tokens if len(t) > 2 and t not in STOP_WORDS]

    freq = Counter(tokens)
    return freq.most_common(top_n)

def analyze_ats_gaps(user_data: dict, jd_text: str) -> dict:
    """Compare JD keywords vs resume content to find ATS gaps."""

    resume_parts = []
    resume_parts.append(user_data.get("summary", ""))
    for exp in user_data.get("experience", []):
        resume_parts.append(exp.get("title", ""))
        resume_parts.append(exp.get("company", ""))
        resume_parts.extend(exp.get("bullets", []))
    for proj in user_data.get("projects", []):
        resume_parts.append(proj.get("name", ""))
        resume_parts.append(proj.get("tech", ""))
        resume_parts.extend(proj.get("bullets", []))
    for edu in user_data.get("education", []): 
        resume_parts.append(edu.get("degree", ""))
        resume_parts.append(edu.get("field", ""))
    for cat, skills in user_data.get("skills", {}).items():
        resume_parts.extend(skills)

    resume_text = " ".join(resume_parts).lower()
    resume_words = set(resume_text.split())

    jd_keywords = extract_keywords(jd_text, top_n=50)
    gap_keywords = []
    present_keywords = []

    for kw, freq in jd_keywords:

        found = kw in resume_words or any(
            kw in w or w in kw for w in resume_words if len(w) > 3
        )
        if found:
            present_keywords.append((kw, freq))
        else:
            gap_keywords.append((kw, freq))

    coverage = len(present_keywords) / max(len(jd_keywords), 1) * 100
    return {
        "jd_top_keywords": jd_keywords[:20],
        "gap_keywords": gap_keywords[:15],
        "present_keywords": present_keywords[:15],
        "coverage_pct": round(coverage, 1),
        "top_gaps": [k for k, _ in gap_keywords[:8]]
    }

def draw_background(canvas, doc):
    """Draw the warm matte paper background for every page."""
    canvas.saveState()
    canvas.setFillColor(HexColor(STITCH_TOKENS["palette"]["page"]))
    canvas.rect(0, 0, letter[0], letter[1], fill=1, stroke=0)

    # Paint the right sidebar for two-column templates
    if not STITCH_TOKENS["rules"].get("single_column"):
        S = STITCH_TOKENS["spacing"]
        content_width = letter[0] - S["margin_left"] * inch - S["margin_right"] * inch
        right_col_x = S["margin_left"] * inch + content_width * 0.62
        canvas.setFillColor(HexColor("#D6E4EC"))
        canvas.rect(right_col_x, 0, letter[0] - right_col_x, letter[1], fill=1, stroke=0)

    canvas.restoreState()

