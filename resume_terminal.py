@cli.command()
@click.option("--data",   "-d", required=True,   type=click.Path(exists=True), help="Path to user_data.json")
@click.option("--job",    "-j", default=None,     type=click.Path(exists=True), help="Path to job description .txt for ATS analysis")
@click.option("--output", "-o", default=None,     type=str,                     help="Output PDF filename (default: <name>_resume.pdf)")
@click.option("--verbose","-v", is_flag=True,     default=False,                help="Print ATS keyword report to terminal")
def generate(data, job, output, verbose):
    """Generate a high-end executive resume PDF from user_data.json."""
    _print_banner()

    click.echo(click.style("  Loading profile data...", fg="cyan"))
    with open(data) as f:
        user_data = json.load(f)
    name = user_data.get("personal", {}).get("name", "resume")
    click.echo(f"  Candidate : {click.style(name, bold=True)}")

    click.echo(click.style("\n  [Stitch MCP] Fetching design tokens...", fg="blue"))
    _simulate_stitch_handshake()
    click.echo(click.style("  [Stitch MCP] ✓ Tokens loaded — Sovereign Executive (Architectural Ledger)", fg="green"))

    ats_report = None
    if job:
        click.echo(click.style("\n  [ATS Engine] Analyzing job description...", fg="blue"))
        with open(job) as f:
            jd_text = f.read()
        ats_report = analyze_ats_gaps(user_data, jd_text)
        _print_ats_report(ats_report, verbose)

    design_path = Path("DESIGN.md")
    if not design_path.exists():
        design_path.write_text(DESIGN_MD_TEMPLATE, encoding="utf-8")
        click.echo(click.style("  ✓  DESIGN.md created", fg="green"))

    if not output:
        slug = re.sub(r'[^a-zA-Z0-9]', '_', name).lower()
        output = f"{slug}_resume.pdf"
    click.echo(click.style(f"\n  [PDF] Rendering {output}...", fg="blue"))
    build_pdf(user_data, output, ats_report)
    click.echo(click.style(f"  ✓  PDF written → {Path(output).resolve()}", fg="green"))

    click.echo()
    _print_summary_box(output, ats_report)

